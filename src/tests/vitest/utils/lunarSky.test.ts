import proj4 from "proj4";
import { getLunarSunEarthPositions, getMapAzimuthFromTrueAzimuth } from "utils/mapping/lunarSky";
import reference from "../fixtures/lunarSky/reference.json";

const RADIUS = 1737400;
const LANDER: AEGISPoint = { lat: -84.223397, lng: 33.5021945 };
const LANDER_ELEVATION = 5414.891;
const SOUTH_POLE_STEREO =
  "+proj=stere +lat_0=-90 +lon_0=0 +k=1 +x_0=0 +y_0=0 +a=1737400 +b=1737400 +units=m +no_defs";
const projectSouthPole = (p: AEGISPoint) => proj4(SOUTH_POLE_STEREO, [p.lng, p.lat]);
const DEG = Math.PI / 180;
const BODIES = ["sun", "earth"] as const;

const angularDifference = (a: number, b: number) => Math.abs(((((a - b) % 360) + 540) % 360) - 180);

// Haversine angular separation is stable for small errors and near zenith, where
// azimuth by itself is ill-conditioned. This also handles the 0/360 discontinuity.
function separationDegrees(a: LunarSkyPosition, b: LunarSkyPosition): number {
  const h =
    Math.sin(((a.elevation - b.elevation) * DEG) / 2) ** 2 +
    Math.cos(a.elevation * DEG) *
      Math.cos(b.elevation * DEG) *
      Math.sin(((a.azimuth - b.azimuth) * DEG) / 2) ** 2;
  return (2 * Math.asin(Math.sqrt(Math.min(1, Math.max(0, h))))) / DEG;
}

function positionsFor(sample: (typeof reference.cases)[number]) {
  return getLunarSunEarthPositions(
    sample.point,
    sample.heightMeters,
    sample.radiusMeters,
    Date.parse(sample.utc)
  );
}

// Independent NASA/JPL oracles, NOT snapshots generated by this implementation.
// Sources, regeneration, model differences, and scope: ../fixtures/lunarSky/README.md.
// These are regression acceptance limits for this corpus, not universal error bounds.
describe.each([
  { source: "spice" as const, directionTolerance: 0.005, azimuthTolerance: 0.01 },
  { source: "horizons" as const, directionTolerance: 0.01, azimuthTolerance: 0.05 },
])(
  "getLunarSunEarthPositions against $source",
  ({ source, directionTolerance, azimuthTolerance }) => {
    it.each(reference.cases)("matches both target centers at $id", (sample) => {
      const actual = positionsFor(sample);
      for (const body of BODIES) {
        const expected = sample[source][body];
        const value = actual[body];
        const context = `${source} ${sample.id} ${body}: ${JSON.stringify({ actual: value, expected })}`;
        expect(Number.isFinite(value.azimuth), context).toBe(true);
        expect(Number.isFinite(value.elevation), context).toBe(true);
        expect(value.azimuth, context).toBeGreaterThanOrEqual(0);
        expect(value.azimuth, context).toBeLessThan(360);
        expect(value.elevation, context).toBeGreaterThanOrEqual(-90);
        expect(value.elevation, context).toBeLessThanOrEqual(90);
        expect(separationDegrees(value, expected), context).toBeLessThan(directionTolerance);
        expect(Math.abs(value.elevation - expected.elevation), context).toBeLessThan(
          directionTolerance
        );
        // Near zenith/nadir, tiny direction errors can produce large azimuth
        // changes. The direction/elevation bounds above still apply everywhere.
        if (Math.abs(expected.elevation) < 80) {
          expect(angularDifference(value.azimuth, expected.azimuth), context).toBeLessThan(
            azimuthTolerance
          );
        }
      }
    });
  }
);

describe("getLunarSunEarthPositions", () => {
  it("retains near-side/south-pole coverage across day, night, seasons, and azimuth wrap", () => {
    expect(reference.cases).toHaveLength(99);
    expect(new Set(reference.cases.map((sample) => sample.site)).size).toBe(9);
    for (const sample of reference.cases) {
      expect(Math.abs(sample.point.lng)).toBeLessThan(90);
      expect(sample.point.lat).toBeLessThanOrEqual(45);
    }
    const august = reference.cases.filter(
      (sample) => sample.site === "lander" && sample.utc.startsWith("2028-08")
    );
    expect(august.some((sample) => sample.spice.sun.elevation < -1)).toBe(true);
    expect(august.some((sample) => sample.spice.sun.elevation > 1)).toBe(true);
    expect(august.some((sample) => Math.abs(sample.spice.sun.elevation) < 0.5)).toBe(true);
    expect(august.some((sample) => sample.spice.sun.azimuth < 15)).toBe(true);
    expect(august.some((sample) => sample.spice.sun.azimuth > 345)).toBe(true);
    expect(reference.cases.some((sample) => sample.spice.earth.elevation > 85)).toBe(true);
    expect(reference.cases.some((sample) => sample.spice.earth.elevation < 0)).toBe(true);
  });

  it.each(reference.cases.filter((sample) => sample.site === "above-datum"))(
    "matches SPICE's change in Earth parallax with observer height at $utc",
    (high) => {
      const low = reference.cases.find(
        (sample) => sample.site === "below-datum" && sample.utc === high.utc
      );
      const actualChange = positionsFor(high).earth.elevation - positionsFor(low).earth.elevation;
      const expectedChange = high.spice.earth.elevation - low.spice.earth.elevation;
      // Differencing cancels most ephemeris error and detects omitted height or
      // meter/kilometer mistakes that the absolute-position tolerance could hide.
      expect(expectedChange).toBeLessThan(-0.01);
      expect(Math.abs(actualChange - expectedChange)).toBeLessThan(0.00001);
    }
  );

  it.each([-60, 0, 33.5021945, 60])(
    "treats longitude %s and longitude +360 as the same site",
    (lng) => {
      const epoch = Date.parse("2028-08-04T22:00:00Z");
      const a = getLunarSunEarthPositions(
        { lat: LANDER.lat, lng },
        LANDER_ELEVATION,
        RADIUS,
        epoch
      );
      const b = getLunarSunEarthPositions(
        { lat: LANDER.lat, lng: lng + 360 },
        LANDER_ELEVATION,
        RADIUS,
        epoch
      );
      for (const body of BODIES) expect(separationDegrees(a[body], b[body])).toBeLessThan(1e-10);
    }
  );

  it("uses height relative to the supplied reference radius", () => {
    const epoch = Date.parse("2028-08-04T22:00:00Z");
    const a = getLunarSunEarthPositions(LANDER, LANDER_ELEVATION, RADIUS, epoch);
    const b = getLunarSunEarthPositions(LANDER, LANDER_ELEVATION - 1000, RADIUS + 1000, epoch);
    for (const body of BODIES) expect(separationDegrees(a[body], b[body])).toBeLessThan(1e-10);
  });

  it("keeps Earth within libration range of the near-side horizon at the south pole", () => {
    const start = new Date("2028-01-01T00:00:00Z").getTime();
    for (let day = 0; day < 60; day++) {
      const { earth } = getLunarSunEarthPositions(
        { lat: -90, lng: 0 },
        0,
        RADIUS,
        start + day * 86400000
      );
      expect(Math.abs(earth.elevation)).toBeLessThan(8);
    }
  });
});

describe("getMapAzimuthFromTrueAzimuth", () => {
  it.each([0, 45, 90, 180, 270])("projects bearing %s at the exact south pole", (bearing) => {
    expect(
      getMapAzimuthFromTrueAzimuth({ lat: -90, lng: 0 }, bearing, projectSouthPole)
    ).toBeCloseTo(bearing, 3);
  });

  it.each([-60, 0, 33, 60])(
    "keeps projected sky directions continuous at the south pole at longitude %s",
    (lng) => {
      const epoch = new Date("2028-08-04T22:00:00Z").getTime();
      const nearPole = { lat: -89.9999, lng };
      const atPole = { lat: -90, lng };
      const near = getLunarSunEarthPositions(nearPole, 0, RADIUS, epoch);
      const at = getLunarSunEarthPositions(atPole, 0, RADIUS, epoch);
      for (const body of ["sun", "earth"] as const) {
        expect(
          angularDifference(
            getMapAzimuthFromTrueAzimuth(atPole, at[body].azimuth, projectSouthPole),
            getMapAzimuthFromTrueAzimuth(nearPole, near[body].azimuth, projectSouthPole)
          )
        ).toBeLessThan(0.001);
      }
    }
  );

  it.each([-90, -89.9999, -84.223397, -45])(
    "matches analytic south-polar stereographic grid convergence at latitude %s",
    (lat) => {
      // For lon_0=0, south-polar stereographic has grid bearing = true bearing + longitude.
      // This expected value uses projection geometry, not another call to the function under test.
      for (const lng of [-75, -33, 0, 33, 75]) {
        for (const bearing of [0, 0.001, 45, 90, 180, 270, 359.999]) {
          const actual = getMapAzimuthFromTrueAzimuth({ lat, lng }, bearing, projectSouthPole);
          expect(angularDifference(actual, bearing + lng)).toBeLessThan(0.001);
        }
      }
    }
  );

  it("keeps the same physical direction at the exact south pole across longitude conventions", () => {
    const epoch = Date.parse("2028-08-04T22:00:00Z");
    const origin = { lat: -90, lng: 0 };
    const base = getLunarSunEarthPositions(origin, 0, RADIUS, epoch);
    for (const lng of [-75, -33, 33, 75]) {
      const point = { lat: -90, lng };
      const sky = getLunarSunEarthPositions(point, 0, RADIUS, epoch);
      for (const body of BODIES) {
        expect(Math.abs(sky[body].elevation - base[body].elevation)).toBeLessThan(1e-10);
        expect(
          angularDifference(
            getMapAzimuthFromTrueAzimuth(point, sky[body].azimuth, projectSouthPole),
            getMapAzimuthFromTrueAzimuth(origin, base[body].azimuth, projectSouthPole)
          )
        ).toBeLessThan(1e-7);
      }
    }
  });

  it("points true north radially away from the pole in south polar stereographic", () => {
    // lng 0 lies on the map's +y axis, so north (away from the pole) is map-up.
    expect(getMapAzimuthFromTrueAzimuth({ lat: -85, lng: 0 }, 0, projectSouthPole)).toBeCloseTo(
      0,
      3
    );
    // lng 90 lies on the +x axis, so north is map-right.
    expect(getMapAzimuthFromTrueAzimuth({ lat: -85, lng: 90 }, 0, projectSouthPole)).toBeCloseTo(
      90,
      3
    );
  });

  it("rotates every azimuth by the same offset at a point", () => {
    const north = getMapAzimuthFromTrueAzimuth(LANDER, 0, projectSouthPole);
    const east = getMapAzimuthFromTrueAzimuth(LANDER, 90, projectSouthPole);
    expect((east - north + 360) % 360).toBeCloseTo(90, 3);
  });

  it("falls back to the true azimuth when the projection returns invalid values", () => {
    expect(getMapAzimuthFromTrueAzimuth(LANDER, 42, () => [NaN, NaN])).toBe(42);
    expect(getMapAzimuthFromTrueAzimuth(LANDER, 42, () => [Infinity, 0])).toBe(42);
  });

  it("falls back to the true azimuth when the projection collapses the tangent step", () => {
    expect(getMapAzimuthFromTrueAzimuth(LANDER, 42, () => [10, 10])).toBe(42);
  });
});
